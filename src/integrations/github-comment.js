import { execSync } from "node:child_process";

const MAX_COMMENT = 64000;

export function formatComment(verdict) {
  const lines = [];
  lines.push("## AI-EMPIRE verdict: **" + verdict.verdict + "**");
  lines.push("");
  lines.push("Score: " + verdict.score + "/100");
  lines.push("Intent: " + verdict.intent);
  lines.push("");
  lines.push("### Reasons");
  for (const r of verdict.reasons) lines.push("- " + r);
  if (verdict.regressions && verdict.regressions.length > 0) {
    lines.push("");
    lines.push("## Regressions");
    for (const reg of verdict.regressions) {
      if (reg.severity || reg.file || reg.kind || reg.description) {
        lines.push("- **[" + reg.severity + "]** `" + reg.file + "` (" + reg.kind + "): " + reg.description);
      } else if (reg.message) {
        const prefix = reg.id ? "**" + reg.id + "**: " : "";
        lines.push("- " + prefix + reg.message);
      } else {
        lines.push("- " + JSON.stringify(reg));
      }
    }
  }
  if (verdict.appliedFixes && verdict.appliedFixes.length > 0) {
    lines.push("");
    lines.push("### Applied fixes");
    for (const f of verdict.appliedFixes) lines.push("- " + f);
  }
  lines.push("");
  lines.push("_Generated by ai-empire — see workflow artifact for full report._");
  let body = lines.join("\n");
  if (body.length > MAX_COMMENT) body = body.slice(0, MAX_COMMENT - 80) + "\n\n_…truncated to 64000 chars; see full report artifact._";
  return body;
}

export function postComment({ pr, body, repo }) {
  // gh CLI is provided by GitHub-hosted runners; consumers can stub this
  const args = ["pr", "comment", String(pr), "--body", body];
  if (repo) args.unshift("--repo", repo);
  execSync("gh " + args.map((a) => JSON.stringify(a)).join(" "), { stdio: "inherit" });
}
